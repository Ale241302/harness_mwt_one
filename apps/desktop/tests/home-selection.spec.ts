import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, describe, expect, it } from 'vitest'
import {
  DESKTOP_MODE_FILENAME,
  assertSeparateHome,
  readStoredMode,
  resolveHomeSelection,
  writeStoredMode,
} from '../src/home-selection.ts'
import {
  LOCAL_IDENTITY_FILENAME,
  LOCAL_IDENTITY_PATCH_FILENAME,
  ensureLocalIdentity,
  readLocalIdentity,
  writeLocalIdentityPatch,
} from '../src/local-identity.ts'

let dir: string | undefined
function home(): string {
  dir ??= mkdtempSync(join(tmpdir(), 'dsh-desktop-home-'))
  return dir
}

afterEach(() => {
  if (dir !== undefined) rmSync(dir, { recursive: true, force: true })
  dir = undefined
})

describe('local home selection (D08, BASE-01)', () => {
  it('records the first launch as local and reuses it on restart', () => {
    const first = resolveHomeSelection({ home: home(), environment: {}, effective: 'local' })
    expect(first).toMatchObject({ mode: 'local', source: 'first-launch' })
    expect(readStoredMode(home())).toBe('local')
    expect(JSON.parse(readFileSync(join(home(), DESKTOP_MODE_FILENAME), 'utf8'))).toMatchObject({
      schemaVersion: 1,
      mode: 'local',
    })

    const restart = resolveHomeSelection({ home: home(), environment: {}, effective: 'local' })
    expect(restart).toMatchObject({ mode: 'local', source: 'stored' })
  })

  it('accepts an explicit mode that agrees with the launched backend and refuses a contradiction', () => {
    expect(resolveHomeSelection({
      home: home(), environment: { DSH_DESKTOP_MODE: 'local' }, effective: 'local',
    })).toMatchObject({ mode: 'local', source: 'environment' })

    expect(() => resolveHomeSelection({
      home: home(), environment: { DSH_DESKTOP_MODE: 'remote' }, effective: 'local',
    })).toThrow('DSH_DESKTOP_MODE_CONFLICT')
    expect(() => resolveHomeSelection({
      home: home(), environment: { DSH_DESKTOP_MODE: 'sincronizado' }, effective: 'local',
    })).toThrow('DSH_DESKTOP_MODE_INVALID')
  })

  it('lets a later launch change the recorded mode when the environment changes it', () => {
    writeStoredMode(home(), 'remote')
    const selection = resolveHomeSelection({ home: home(), environment: {}, effective: 'local' })
    expect(selection.mode).toBe('local')
    expect(readStoredMode(home())).toBe('local')
  })

  it('refuses a home inside a synchronized folder or a network share', () => {
    expect(() => { assertSeparateHome(join(home(), 'OneDrive', 'harness'), {}) }).toThrow('DSH_DESKTOP_HOME_SYNCED')
    expect(() => { assertSeparateHome(join(home(), 'Dropbox', 'harness'), {}) }).toThrow('DSH_DESKTOP_HOME_SYNCED')
    expect(() => { assertSeparateHome('//server/share/harness', {}) }).toThrow('DSH_DESKTOP_HOME_SYNCED')
    expect(() => { assertSeparateHome(join(home(), 'local', 'harness'), {}) }).not.toThrow()
  })

  it('uses the environment root of a sync client, not only the folder name', () => {
    const syncRoot = join(home(), 'cliente')
    expect(() => { assertSeparateHome(join(syncRoot, 'harness'), { OneDrive: syncRoot }) })
      .toThrow('DSH_DESKTOP_HOME_SYNCED')
    expect(() => { assertSeparateHome(join(home(), 'otro', 'harness'), { OneDrive: syncRoot }) }).not.toThrow()
  })
})

describe('local identity (BASE-01)', () => {
  it('creates one stable identity and keeps it across restarts', () => {
    const created = ensureLocalIdentity(home(), '2026-11-05T10:00:00.000Z')
    expect(created.id).toMatch(/^[0-9a-f-]{36}$/u)
    expect(created.createdAt).toBe('2026-11-05T10:00:00.000Z')
    expect(ensureLocalIdentity(home(), '2026-11-06T10:00:00.000Z')).toEqual(created)
    expect(readLocalIdentity(home())).toEqual(created)
  })

  it('writes its own document and never a remote identity', () => {
    ensureLocalIdentity(home())
    expect(readLocalIdentity(home())).toBeDefined()
    // The remote identity file is what activates the mirror; a local launch must
    // not create it.
    expect(() => readFileSync(join(home(), 'desktop-identity.json'), 'utf8')).toThrow()
    expect(readFileSync(join(home(), LOCAL_IDENTITY_FILENAME), 'utf8')).toContain('schemaVersion')
  })

  it('boots from a local patch with its own owner and no console shares row', () => {
    const identity = ensureLocalIdentity(home())
    const patchPath = writeLocalIdentityPatch(home(), identity, {}, undefined)
    expect(patchPath).toBe(join(home(), LOCAL_IDENTITY_PATCH_FILENAME))
    const patch = readFileSync(patchPath, 'utf8')
    expect(patch).toContain(identity.id)
    expect(patch).toContain('Generated by the Desktop local home')
    expect(patch).not.toContain('faberloom-shares')
    expect(() => readFileSync(join(home(), '.env'), 'utf8')).toThrow()
  })

  it('replaces an unreadable identity instead of failing the launch', () => {    writeFileSync(join(home(), LOCAL_IDENTITY_FILENAME), '{ roto')
    expect(readLocalIdentity(home())).toBeUndefined()
    const replaced = ensureLocalIdentity(home())
    expect(readLocalIdentity(home())).toEqual(replaced)
  })

  it('ignores an identity of another schema version', () => {
    writeFileSync(join(home(), LOCAL_IDENTITY_FILENAME), JSON.stringify({ schemaVersion: 2, id: 'x', createdAt: 'y' }))
    expect(readLocalIdentity(home())).toBeUndefined()
  })
})
